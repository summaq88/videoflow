"""Builds every app icon from branding/image.png (run from the web/ folder; the APK build does this automatically).

Writes: Android launcher icons (all densities, square/round/adaptive), the startup splash screens,
src/lib/logo.ts (in-app header logo) and the favicon in index.html.
"""
import base64, glob, io, os, re
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.dirname(HERE)
RES = os.path.join(WEB, 'android', 'app', 'src', 'main', 'res')
BG = (6, 21, 44)  # the logo's dark navy

src = Image.open(os.path.join(HERE, 'image.png')).convert('RGB')
W, H = src.size
a = np.asarray(src).astype(int)
# The emblem = bright pixels above the name text (the name is unreadable at icon size).
mask = a.max(axis=2) > 90
mask[int(H * 0.705):] = False
ys, xs = np.where(mask)
pad = 12
emblem = src.crop((max(xs.min() - pad, 0), max(ys.min() - pad, 0), min(xs.max() + pad + 1, W), min(ys.max() + pad + 1, H)))


def canvas(n, frac):
    """Square n×n: navy background with a soft blue glow and the emblem at `frac` of the width."""
    c = Image.new('RGB', (n, n), BG)
    g = Image.new('L', (n, n), 0)
    r = n * 0.42
    ImageDraw.Draw(g).ellipse((n / 2 - r, n / 2 - r, n / 2 + r, n / 2 + r), fill=70)
    c = Image.composite(Image.new('RGB', (n, n), (16, 52, 110)), c, g.filter(ImageFilter.GaussianBlur(n * 0.12)))
    w = int(n * frac)
    h = int(w * emblem.height / emblem.width)
    e = emblem.resize((w, h), Image.LANCZOS)
    m = np.clip((np.asarray(e).astype(int).max(axis=2) - 25) * 4, 0, 255).astype('uint8')
    c.paste(e, ((n - w) // 2, (n - h) // 2), Image.fromarray(m).filter(ImageFilter.GaussianBlur(0.6)))
    return c


def masked(img, shape):
    n = img.width
    m = Image.new('L', (n, n), 0)
    d = ImageDraw.Draw(m)
    if shape == 'circle':
        d.ellipse((0, 0, n - 1, n - 1), fill=255)
    else:
        d.rounded_rectangle((0, 0, n - 1, n - 1), radius=n * 0.22, fill=255)
    out = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    out.paste(img, (0, 0), m)
    return out


for name, s in {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}.items():
    d = os.path.join(RES, f'mipmap-{name}')
    os.makedirs(d, exist_ok=True)
    canvas(int(108 * s), 0.60).save(os.path.join(d, 'ic_launcher_foreground.png'))  # adaptive (Android 8+)
    n = int(48 * s)
    masked(canvas(n * 4, 0.80), 'rounded').resize((n, n), Image.LANCZOS).save(os.path.join(d, 'ic_launcher.png'))
    masked(canvas(n * 4, 0.72), 'circle').resize((n, n), Image.LANCZOS).save(os.path.join(d, 'ic_launcher_round.png'))

with open(os.path.join(RES, 'values', 'ic_launcher_background.xml'), 'w') as f:
    f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#06152C</color>\n</resources>\n')

for f in glob.glob(os.path.join(RES, 'drawable*', 'splash.png')):
    w, h = Image.open(f).size
    c = Image.new('RGB', (w, h), BG)
    side = int(min(w, h) * 0.62)
    c.paste(src.resize((side, side), Image.LANCZOS), ((w - side) // 2, (h - side) // 2))
    c.save(f, optimize=True)

logo = masked(canvas(512, 0.84), 'rounded').resize((96, 96), Image.LANCZOS)
buf = io.BytesIO()
logo.save(buf, 'PNG', optimize=True)
uri = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
with open(os.path.join(WEB, 'src', 'lib', 'logo.ts'), 'w') as f:
    f.write(f"// Generated by branding/make_icons.py from branding/image.png.\nexport const LOGO_URI = '{uri}';\n")

idx = os.path.join(WEB, 'index.html')
html = open(idx).read()
html = re.sub(r'<link rel="icon"[^>]*/>', f'<link rel="icon" type="image/png" href="{uri}" />', html, count=1)
open(idx, 'w').write(html)
print('icons generated')
